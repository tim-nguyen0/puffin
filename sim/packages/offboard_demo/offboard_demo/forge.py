"""renders a whole ros 2 package around one mission plan. no ros imports so
it tests anywhere.

the forge exists so a primed mission can outlive the mission host: instead of
an in-process executor the plan gets its own package, its own `ros2 run` entry
point and its own supervisord program, which means it survives a host restart
and shows up in `supervisorctl status` like any other process.

the generated node is deliberately thin. it embeds the plan and hands it
straight to mission_node.run_executor, so a forged node and a host child fly
identical code - the only difference is who owns the process.

templates substitute a __FORGE_NAME__/__FORGE_PLAN__ sentinel rather than
str.format or Template: the rendered files are full of braces and $vars of
their own.
"""

